# ---------- Chart 3: Average CGPA per team with overall line ----------
def plot_average_cgpa_per_team(team_data_rows, show_hist=True):
    if not team_data_rows:
        print("No data to plot (CGPA).")
        return

    teams_dict = _teams_from_rows(team_data_rows)
    if not teams_dict:
        print("No teams found (CGPA).")
        return

    # Locate a CGPA/GPA-like column
    any_row = next(iter(teams_dict.values()))[0]
    cgpa_col = _find_field_name(any_row, ["CGPA", "GPA", "Cgpa", "Gpa"])
    if cgpa_col is None:
        print("Couldn't find a 'CGPA/GPA' column.")
        return

    team_ids, team_avgs, all_cgpas = [], [], []

    for tid, members in sorted(teams_dict.items(), key=lambda kv: kv[0]):
        vals = []
        for r in members:
            v = _to_float(r.get(cgpa_col))
            if v is not None:
                vals.append(v)
                all_cgpas.append(v)
        if vals:
            avg = sum(vals) / len(vals)
            team_ids.append(str(tid))
            team_avgs.append(avg)

    overall_avg = (sum(all_cgpas) / len(all_cgpas)) if all_cgpas else 0.0

    fig2 = plt.figure(figsize=(7.5, 4.5))
    ax2 = fig2.gca()
    bins = max(5, min(12, len(team_avgs)))
    ax2.hist(team_avgs, bins=bins)
    ax2.set_xlabel("Team average CGPA")
    ax2.set_ylabel("Number of teams")
    ax2.set_title("Distribution of Team Average CGPA")
    ax2.axvline(overall_avg, color="red", linewidth=2)
    ymax = ax2.get_ylim()[1]
    ax2.text(
        overall_avg,
        ymax * 0.95,
        f"{overall_avg:.2f}",
        ha="left",
        va="top",
        fontsize=9,
        color="red",
    )
    plt.tight_layout()
    plt.show()


