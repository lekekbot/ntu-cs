# ---------- Shared helpers ----------
def _find_field_name(sample_row, candidates):
    lower_map = {k.lower(): k for k in sample_row.keys()}
    for cand in candidates:
        if cand.lower() in lower_map:
            return lower_map[cand.lower()]
    return None


def _teams_from_rows(rows):
    teams = {}
    for r in rows:
        tid = (
            r.get("Team Assigned")
            or r.get("team assigned")
            or r.get("team")
            or r.get("Team")
        )
        if tid is None:
            continue
        teams.setdefault(str(tid), []).append(r)
    return teams  # dict: {team_id: [rows...]}


def _to_float(val):
    if val is None:
        return None
    s = str(val).strip().replace(",", "")
    if not s:
        return None
    try:
        return float(s)
    except:
        return None


def _gender_code(val):
    """Return 'M' or 'F' if clearly identifiable, else None."""
    if val is None:
        return None
    s = str(val).strip().lower()
    if not s:
        return None
    if s[0] == "m":
        return "M"
    if s[0] == "f":
        return "F"
    return None


# ---------- Chart 1: Gender-mix distribution ----------
def plot_gender_mix_distribution(team_data_rows, team_size_hint=None):
    if not team_data_rows:
        print("No data to plot (gender mix).")
        return

    teams_dict = _teams_from_rows(team_data_rows)
    if not teams_dict:
        print("No teams found (gender mix).")
        return

    # Try to locate the gender column
    any_row = next(iter(teams_dict.values()))[0]
    gender_col = _find_field_name(any_row, ["Gender", "Sex"])
    if gender_col is None:
        print("Couldn't find a 'Gender' column (tried: Gender/Sex).")
        return

    from collections import Counter, defaultdict

    comp_counts_by_size = defaultdict(Counter)  # {size: Counter("xM+yF" -> n)}
    size_counts = Counter()

    for members in teams_dict.values():
        m = f = 0
        for r in members:
            g = _gender_code(r.get(gender_col))
            if g == "M":
                m += 1
            elif g == "F":
                f += 1
        size = len(members)
        if team_size_hint is not None:
            # lock bins to a fixed size if desired
            if m + f != team_size_hint:
                # if blanks/others exist, force F from hint
                f = max(0, team_size_hint - m)
            size = team_size_hint
        else:
            size = m + f  # only count rows recognized as M/F

        label = f"{m}M+{f}F"
        comp_counts_by_size[size][label] += 1
        size_counts[size] += 1

    if not size_counts:
        print("No recognizable M/F data to plot.")
        return

    primary_size = max(size_counts.items(), key=lambda kv: kv[1])[0]

    def _plot_size(size, counts):
        labels = [f"{m}M+{size-m}F" for m in range(size, -1, -1)]
        values = [counts.get(lbl, 0) for lbl in labels]

        fig = plt.figure(figsize=(8, 4.5))
        ax = fig.gca()
        ax.bar(range(len(labels)), values)
        ax.set_xticks(range(len(labels)))
        ax.set_xticklabels(labels)
        ax.set_xlabel("Team gender composition")
        ax.set_ylabel("Number of teams")
        ax.set_title(f"Gender Mix Distribution (Team Size {size})")
        for x, v in enumerate(values):
            if v > 0:
                ax.text(x, v, str(v), ha="center", va="bottom", fontsize=9)
        plt.tight_layout()
        plt.show()

    # plot the most common team size first
    _plot_size(primary_size, comp_counts_by_size[primary_size])

    # plot other sizes if present
    for size, counts in comp_counts_by_size.items():
        if size == primary_size:
            continue
        _plot_size(size, counts)


