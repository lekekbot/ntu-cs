def plot_school_count_distribution(team_data_rows):
    if not team_data_rows:
        print("No data to plot (schools).")
        return

    teams_dict = _teams_from_rows(team_data_rows)
    if not teams_dict:
        print("No teams found (schools).")
        return

    # Guess a school-like column name
    any_row = next(iter(teams_dict.values()))[0]
    school_col = _find_field_name(
        any_row, ["School", "Faculty", "Programme", "Program", "Department"]
    )
    if school_col is None:
        print("Couldn't find a 'School/Faculty/Programme/Program/Department' column.")
        return

    from collections import Counter

    counter = Counter()
    max_sch = 0

    for members in teams_dict.values():
        schools = []
        for r in members:
            val = r.get(school_col)
            val = "" if val is None else str(val).strip()
            if val:
                schools.append(val)
        distinct = len(set(schools))
        counter[distinct] += 1
        if distinct > max_sch:
            max_sch = distinct

    xs = list(range(1, max_sch + 1)) if max_sch > 0 else [0]
    ys = [counter.get(x, 0) for x in xs]

    fig = plt.figure(figsize=(8, 4.5))
    ax = fig.gca()
    ax.bar(range(len(xs)), ys)
    ax.set_xticks(range(len(xs)))
    ax.set_xticklabels([str(x) for x in xs])
